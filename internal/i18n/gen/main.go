// Command gen 从 locales/*.yaml 生成消息键常量, 并校验双语完整性.
// 运行方式: go generate ./internal/i18n/...
package main

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"text/template"

	"gopkg.in/yaml.v3"
)

func main() {
	dir := filepath.Join("locales")
	langs := []string{"en", "zh"}

	// 1. 加载全部语言文件.
	messages := map[string]map[string]string{} // lang -> key -> template
	for _, lang := range langs {
		data, err := os.ReadFile(filepath.Join(dir, lang+".yaml"))
		if err != nil {
			fatal("读取 %s.yaml 失败: %v", lang, err)
		}
		m := map[string]string{}
		if err := yaml.Unmarshal(data, &m); err != nil {
			fatal("解析 %s.yaml 失败: %v", lang, err)
		}
		messages[lang] = m
	}

	// 2. 校验所有语言 key 集合一致.
	base := messages[langs[0]]
	for _, lang := range langs[1:] {
		m := messages[lang]
		for k := range base {
			if _, ok := m[k]; !ok {
				fatal("语言 %s 缺少消息: %s", lang, k)
			}
		}
		for k := range m {
			if _, ok := base[k]; !ok {
				fatal("语言 %s 存在多余消息: %s", lang, k)
			}
		}
	}

	// 3. 校验模板可解析.
	for _, lang := range langs {
		for k, v := range messages[lang] {
			if _, err := template.New(k).Parse(v); err != nil {
				fatal("语言 %s 消息 %s 模板解析失败: %v", lang, k, err)
			}
		}
	}

	// 4. 生成常量文件.
	keys := make([]string, 0, len(base))
	for k := range base {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var b strings.Builder
	b.WriteString("// Code generated by go generate; DO NOT EDIT.\n")
	b.WriteString("// Source: internal/i18n/locales/*.yaml\n\n")
	b.WriteString("package i18n\n\n")
	b.WriteString("// Key 是本地化消息键, 由 locales/*.yaml 生成.\n")
	b.WriteString("type Key string\n\n")
	b.WriteString("const (\n")
	for _, k := range keys {
		b.WriteString(fmt.Sprintf("\t%s Key = %q\n", k, k))
	}
	b.WriteString(")\n")

	out := filepath.Join("messages_gen.go")
	// 生成的代码必须 gofmt 合规: 直接用 go/format 输出,
	// 避免生成后再手动格式化 (历史版本曾因此提交未对齐的生成文件).
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		fatal("格式化生成代码失败: %v", err)
	}
	if err := os.WriteFile(out, src, 0o644); err != nil {
		fatal("写入 %s 失败: %v", out, err)
	}
	fmt.Printf("generated %d message keys (%d languages, all valid)\n", len(keys), len(langs))
}

func fatal(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "gen: "+format+"\n", args...)
	os.Exit(1)
}
